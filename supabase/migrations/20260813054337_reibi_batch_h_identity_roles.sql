-- Batch H: one trusted identity registry for SleepM, REIBI L5 and distributors.
-- Authorization remains server-side. Browser roles have no direct access.

alter table public.reibi_internal_users
  drop constraint if exists reibi_internal_users_internal_role_check;

alter table public.reibi_internal_users
  add column profile_id uuid references public.profiles(id) on delete restrict,
  add column org_code text references public.reibi_enterprises(org_code) on update cascade on delete restrict,
  add column department_id bigint references public.reibi_departments(id) on delete restrict,
  add column staff_id bigint references public.reibi_staff(id) on delete set null,
  add column distributor_id bigint references public.reibi_distributors(id) on delete restrict,
  add column permission_overrides jsonb not null default '[]'::jsonb,
  add column invited_at timestamptz,
  add column last_login_at timestamptz,
  add column created_by uuid references public.reibi_internal_users(auth_user_id) on delete set null,
  add column updated_by uuid references public.reibi_internal_users(auth_user_id) on delete set null,
  add constraint reibi_internal_users_role_check check (
    internal_role in (
      'individual', 'member', 'dept_head', 'admin_hr', 'admin_finance',
      'admin_it', 'admin', 'occupational_health', 'reibi_super',
      'reibi_finance', 'reibi_data', 'reibi_cs',
      'partner_primary', 'partner_sub'
    )
  ),
  add constraint reibi_internal_users_profile_scope_check check (
    (
      internal_role in (
        'individual', 'member', 'dept_head', 'admin_hr', 'admin_finance',
        'admin_it', 'admin', 'occupational_health'
      )
      and profile_id is not null
      and profile_id = auth_user_id
    )
    or (
      internal_role not in (
        'individual', 'member', 'dept_head', 'admin_hr', 'admin_finance',
        'admin_it', 'admin', 'occupational_health'
      )
      and profile_id is null
    )
  ),
  add constraint reibi_internal_users_org_scope_check check (
    (
      internal_role in (
        'member', 'dept_head', 'admin_hr', 'admin_finance', 'admin_it',
        'admin', 'occupational_health'
      )
      and org_code is not null
    )
    or (
      internal_role not in (
        'member', 'dept_head', 'admin_hr', 'admin_finance', 'admin_it',
        'admin', 'occupational_health'
      )
      and org_code is null
    )
  ),
  add constraint reibi_internal_users_department_scope_check check (
    (
      internal_role in ('member', 'dept_head', 'admin_hr', 'admin_finance', 'admin_it')
      and department_id is not null
    )
    or (
      internal_role not in ('member', 'dept_head', 'admin_hr', 'admin_finance', 'admin_it')
      and department_id is null
    )
  ),
  add constraint reibi_internal_users_distributor_scope_check check (
    (
      internal_role in ('partner_primary', 'partner_sub')
      and distributor_id is not null
    )
    or (
      internal_role not in ('partner_primary', 'partner_sub')
      and distributor_id is null
    )
  ),
  add constraint reibi_internal_users_permission_overrides_array_check
    check (jsonb_typeof(permission_overrides) = 'array');

