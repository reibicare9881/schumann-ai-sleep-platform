create or replace function public.reibi_validate_identity_scope()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_department_org text;
  v_distributor_type text;
begin
  if new.department_id is not null then
    select e.org_code into v_department_org
    from public.reibi_departments d
    join public.reibi_enterprises e on e.id = d.enterprise_id
    where d.id = new.department_id and d.is_active;

    if v_department_org is null or v_department_org <> new.org_code then
      raise exception 'department does not belong to the selected active organization';
    end if;
  end if;

  if new.distributor_id is not null then
    select distributor_type into v_distributor_type
    from public.reibi_distributors
    where id = new.distributor_id and status = 'active';

    if v_distributor_type is null
       or (new.internal_role = 'partner_primary' and v_distributor_type <> 'primary')
       or (new.internal_role = 'partner_sub' and v_distributor_type <> 'sub') then
      raise exception 'distributor type does not match the selected partner role';
    end if;
  end if;

  return new;
end;
$$;

create trigger reibi_internal_users_validate_scope
before insert or update of internal_role, org_code, department_id, distributor_id
on public.reibi_internal_users
for each row execute function public.reibi_validate_identity_scope();

create or replace function public.reibi_touch_identity_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger reibi_internal_users_touch_updated_at
before update on public.reibi_internal_users
for each row execute function public.reibi_touch_identity_updated_at();

